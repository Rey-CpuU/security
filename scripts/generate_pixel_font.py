def build_pixel_font(ttf_path: str, woff_path: str):
    fb = FontBuilder(1000, isTTF=True)

    glyph_order = ['.notdef']
    cmap = {}
    glyphs = {}
    metrics = {}

    # Empty .notdef
    pen_notdef = TTGlyphPen(None)
    # Square border for notdef
    pen_notdef.moveTo((100, 0))
    pen_notdef.lineTo((700, 0))
    pen_notdef.lineTo((700, 800))
    pen_notdef.lineTo((100, 800))
    pen_notdef.closePath()
    pen_notdef.moveTo((200, 100))
    pen_notdef.lineTo((200, 700))
    pen_notdef.lineTo((600, 700))
    pen_notdef.lineTo((600, 100))
    pen_notdef.closePath()
    glyphs['.notdef'] = pen_notdef.glyph()
    metrics['.notdef'] = (800, 100)

    for code in range(32, 127):
        name = f"uni{code:04X}"
        if code == 32:
            name = "space"
        glyph_order.append(name)
        cmap[code] = name

        bitmap = FONT_BITMAPS.get(code, [0]*8)
        pen = TTGlyphPen(None)

        # Draw 8x8 pixel blocks
        # Grid: col 0..7 (width 100 each = 800), row 0..7 (height 100 each = 800)
        has_pixel = False
        for r in range(8):
            row_byte = bitmap[r]
            for c in range(8):
                if (row_byte >> (7 - c)) & 1:
                    has_pixel = True
                    x0 = c * 100
                    y0 = (7 - r) * 100
                    x1 = x0 + 100
                    y1 = y0 + 100
                    pen.moveTo((x0, y0))
                    pen.lineTo((x1, y0))
                    pen.lineTo((x1, y1))
                    pen.lineTo((x0, y1))
                    pen.closePath()

        glyphs[name] = pen.glyph()
        metrics[name] = (800, 0 if code == 32 else 50)

    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({
        'familyName': 'PressStart2P',
        'styleName': 'Regular',
        'uniqueFontIdentifier': 'PressStart2P-Offline-1.0',
        'fullName': 'Press Start 2P Offline',
        'psName': 'PressStart2P-Regular'
    })
    fb.setupOS2(
        sTypoAscender=800,
        sTypoDescender=-200,
        usWinAscent=800,
        usWinDescent=200,
        sxHeight=500,
        sCapHeight=700
    )
    fb.setupPost()
    fb.setupMaxp()

    # Save TTF
    os.makedirs(os.path.dirname(ttf_path), exist_ok=True)
    fb.save(ttf_path)
    print(f"[+] Generated TTF pixel font: {ttf_path} ({os.path.getsize(ttf_path)} bytes)")

    # Save WOFF
    font = fb.font
    font.flavor = 'woff'
    font.save(woff_path)
    print(f"[+] Generated WOFF pixel font: {woff_path} ({os.path.getsize(woff_path)} bytes)")


